package com.example.orders.persistence;

import java.math.BigDecimal;
import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.IdClass;
import jakarta.persistence.Table;

/**
 * Task 3.1 GREEN: one row per line event in table order_line_events of ordersdb.
 * PK = (orderId, sku); messageId UNIQUE (idempotency guard). id is a generated
 * identity column (not the PK). Sibling table order_lines is untouched.
 * Column names follow Spring Boot's default snake_case physical naming strategy:
 * order_id, customer_id, sku, qty, price, line_index, message_id, created_at.
 */
@Entity
@Table(name = "order_line_events")
@IdClass(OrderLineEventId.class)
public class OrderLineEvent {

    // Generated by Postgres identity; Hibernate must omit it from INSERT.
    @Column(insertable = false, updatable = false,
            columnDefinition = "bigint generated by default as identity")
    private Long id;

    @Id
    @Column(nullable = false)
    private String orderId;

    @Column(nullable = false)
    private String customerId;

    @Id
    @Column(nullable = false)
    private String sku;

    @Column(nullable = false)
    private int qty;

    @Column(nullable = false, precision = 18, scale = 4)
    private BigDecimal price;

    @Column(nullable = false)
    private int lineIndex;

    @Column(unique = true, nullable = false)
    private String messageId;

    @Column(nullable = false)
    private Instant createdAt;

    protected OrderLineEvent() {
    }

    public OrderLineEvent(String orderId, String customerId, String sku, int qty, BigDecimal price,
                          int lineIndex, String messageId, Instant createdAt) {
        this.orderId = orderId;
        this.customerId = customerId;
        this.sku = sku;
        this.qty = qty;
        this.price = price;
        this.lineIndex = lineIndex;
        this.messageId = messageId;
        this.createdAt = createdAt;
    }

    public Long getId() { return id; }
    public String getOrderId() { return orderId; }
    public String getCustomerId() { return customerId; }
    public String getSku() { return sku; }
    public int getQty() { return qty; }
    public BigDecimal getPrice() { return price; }
    public int getLineIndex() { return lineIndex; }
    public String getMessageId() { return messageId; }
    public Instant getCreatedAt() { return createdAt; }
}
